// HELPER: SELECT DAILY ROTATING ITEM (Deterministic by day-of-year + Shuffle Support)
// ─────────────────────────────────────────────
export function getDailyGodItem(items, customOffset = 0) {
  if (!items || items.length === 0) return null;
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const targetIdx = Math.abs(dayOfYear + customOffset) % items.length;
  return items[targetIdx];
}
