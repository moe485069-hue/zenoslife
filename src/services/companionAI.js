/**
 * Generate context-aware companion reply
 */
export function generateCompanionReply(companionId, userText) {
  const companion = COMPANION_PERSONAS[companionId] || COMPANION_PERSONAS.companion_sara;
  const text = (userText || '').toLowerCase();

  // Check for game intent
  if (text.includes('بازی') || text.includes('تخته') || text.includes('منچ') || text.includes('game') || text.includes('شطرنج')) {
    return companion.gameResponse;
  }

  // Check for greetings
  if (text.includes('سلام') || text.includes('درود') || text.includes('صبح') || text.includes('شب') || text.includes('hi') || text.includes('hello')) {
    return companion.responses[0];
  }

  // Check for advice / habits
  if (text.includes('عادت') || text.includes('رشد') || text.includes('کار') || text.includes('برنامه') || text.includes('هدف') || text.includes('چالش')) {
    return companion.responses[1];
  }

  // Pick random contextual response
  const pool = companion.responses;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
